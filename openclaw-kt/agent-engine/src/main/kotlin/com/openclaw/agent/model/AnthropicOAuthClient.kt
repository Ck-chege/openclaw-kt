/**
 * OAuth beta headers required by Anthropic when using a setup-token.
 * Mirrors the TypeScript reference in the OpenClaw JS source.
 */
val ANTHROPIC_OAUTH_BETAS = listOf(
    "claude-code-20250219",
    "oauth-2025-04-20",
    "fine-grained-tool-streaming-2025-05-14",
    "interleaved-thinking-2025-05-14"
)

val ANTHROPIC_DEFAULT_BETAS = listOf(
    "fine-grained-tool-streaming-2025-05-14",
    "interleaved-thinking-2025-05-14"
)

/**
 * Returns true if [apiKey] is an Anthropic setup-token (OAuth token).
 * Setup-tokens start with "sk-ant-oat" and are generated by `claude setup-token`.
 */
fun isAnthropicOAuthToken(apiKey: String): Boolean =
    apiKey.trimStart().startsWith("sk-ant-oat")

/**
 * A Ktor [HttpClientEngine] wrapper that intercepts outgoing requests and swaps
 * Anthropic's standard `x-api-key` auth for `Authorization: Bearer` OAuth auth.
 *
 * Koog's AnthropicLLMClient creates its own HttpClient using only the ENGINE from
 * the passed HttpClient (discarding plugins/config), so we must inject auth at the
 * transport/engine level rather than via DefaultRequest or other Ktor plugins.
 *
 * Uses a [tokenSupplier] lambda so the token can be refreshed between calls
 * without recreating the executor.
 */
@OptIn(InternalAPI::class)
private class OAuthHeaderInterceptingEngine(
    private val delegate: HttpClientEngine,
    /** Called per-request so a refreshed token is always used. */
    private val tokenSupplier: suspend () -> String,
    private val betas: List<String>
) : HttpClientEngine by delegate {

    @OptIn(InternalAPI::class)
    override suspend fun execute(data: io.ktor.client.request.HttpRequestData): io.ktor.client.request.HttpResponseData {
        val token = tokenSupplier()

        val modifiedHeaders = Headers.build {
            // Carry over all headers except the ones we're replacing
            data.headers.forEach { name, values ->
                if (!name.equals("x-api-key", ignoreCase = true) &&
                    !name.equals("anthropic-beta", ignoreCase = true) &&
                    !name.equals("Authorization", ignoreCase = true) &&
                    !name.equals("user-agent", ignoreCase = true) &&
                    !name.equals("x-app", ignoreCase = true)
                ) {
                    values.forEach { value -> append(name, value) }
                }
            }
            // Inject OAuth headers
            append(HttpHeaders.Authorization, "Bearer $token")
            append("anthropic-beta", betas.joinToString(","))
            append(HttpHeaders.UserAgent, "claude-cli/2.1.2 (external, cli)")
            append("x-app", "cli")
        }

        val modified = io.ktor.client.request.HttpRequestData(
            url = data.url,
            method = data.method,
            headers = modifiedHeaders,
            body = data.body,
            executionContext = data.executionContext,
            attributes = data.attributes
        )

        return delegate.execute(modified)
    }
}

/**
 * Creates a [PromptExecutor] for Anthropic using OAuth/setup-token auth.
 *
 * The executor wraps [AnthropicLLMClient] with a custom Ktor engine that:
 * - Replaces `x-api-key` with `Authorization: Bearer <token>`
 * - Adds required OAuth beta headers (`claude-code-20250219`, `oauth-2025-04-20`, etc.)
 * - Sets the `user-agent` and `x-app` headers expected by Anthropic OAuth
 * - Calls [tokenSupplier] on every request so refreshed tokens are used automatically
 *
 * @param tokenSupplier Lambda called before each request to get a (possibly refreshed) token
 * @param settings Optional Koog [AnthropicClientSettings] override
 */
fun createAnthropicOAuthExecutor(
    tokenSupplier: suspend () -> String,
    settings: AnthropicClientSettings = AnthropicClientSettings()
): PromptExecutor {
    logger.info { "Creating Anthropic OAuth executor (betas: ${ANTHROPIC_OAUTH_BETAS.joinToString()})" }

    val oauthEngine = OAuthHeaderInterceptingEngine(CIO.create(), tokenSupplier, ANTHROPIC_OAUTH_BETAS)
    val baseHttpClient = HttpClient(oauthEngine)

    val llmClient = AnthropicLLMClient(
        /* apiKey     = */ "",
        /* settings   = */ settings,
        /* httpClient = */ baseHttpClient,
        /* clock      = */ Clock.System
    )

    return SingleLLMPromptExecutor(llmClient)
}

/**
 * Convenience overload for a static token (setup-token path — no auto-refresh).
 */
fun createAnthropicOAuthExecutor(
    token: String,
    settings: AnthropicClientSettings = AnthropicClientSettings()
): PromptExecutor = createAnthropicOAuthExecutor(tokenSupplier = { token }, settings = settings)
